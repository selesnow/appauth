# Слой диалектов: проверки без живой базы (подключения подменяются классами).

fake_conn <- function(class) structure(list(), class = class)

test_that("диалект определяется по классу подключения", {
  expect_identical(aa_dialect(fake_conn("SQLiteConnection")), "sqlite")
  expect_identical(aa_dialect(fake_conn("duckdb_connection")), "duckdb")
  expect_identical(aa_dialect(fake_conn("MariaDBConnection")), "mysql")
  expect_identical(aa_dialect(fake_conn("PqConnection")), "postgres")
  expect_true(is.na(aa_dialect(list())))
  expect_true(is.na(aa_dialect(fake_conn("BigQueryConnection"))))
})

test_that("неподдерживаемая база отклоняется понятной ошибкой", {
  expect_error(aa_check_conn(fake_conn("BigQueryConnection")), class = "appauth_error_connection")
  expect_error(aa_check_conn("not a connection"), class = "appauth_error_connection")
})

test_that("плейсхолдеры заменяются на $n только для PostgreSQL", {
  sql <- "UPDATE users SET role = ? WHERE login = ? AND blocked = ?"
  pg <- fake_conn("PqConnection")

  expect_identical(
    aa_prepare_sql(pg, sql),
    "UPDATE users SET role = $1 WHERE login = $2 AND blocked = $3"
  )
  expect_identical(aa_prepare_sql(pg, "SELECT 1"), "SELECT 1")
  expect_identical(aa_prepare_sql(pg, "SELECT ?"), "SELECT $1")

  for (cls in c("SQLiteConnection", "duckdb_connection", "MariaDBConnection")) {
    expect_identical(aa_prepare_sql(fake_conn(cls), sql), sql)
  }
})

test_that("aa_utc даёт строку UTC и сдвиг в секундах", {
  now <- as.POSIXct("2026-11-05 10:00:00", tz = "UTC")

  expect_identical(aa_utc(0, now), "2026-11-05 10:00:00")
  expect_identical(aa_utc(3600, now), "2026-11-05 11:00:00")
  expect_identical(aa_utc(-86400, now), "2026-11-04 10:00:00")
})

test_that("«вставить, если нет» пишется по диалекту", {
  cols <- c("version", "name")

  expect_match(aa_insert_ignore_sql(fake_conn("MariaDBConnection"), "t", cols), "^INSERT IGNORE INTO t")
  expect_match(aa_insert_ignore_sql(fake_conn("PqConnection"), "t", cols), "ON CONFLICT DO NOTHING$")
  expect_match(aa_insert_ignore_sql(fake_conn("SQLiteConnection"), "t", cols), "ON CONFLICT DO NOTHING$")
})

test_that("типы колонок и автоинкремент зависят от базы", {
  expect_match(aa_pk_column(fake_conn("SQLiteConnection"), "users"), "AUTOINCREMENT")
  expect_match(aa_pk_column(fake_conn("MariaDBConnection"), "users"), "AUTO_INCREMENT")
  expect_match(aa_pk_column(fake_conn("PqConnection"), "users"), "GENERATED BY DEFAULT AS IDENTITY")

  expect_identical(aa_col_types(fake_conn("SQLiteConnection"))$ts, "TEXT")
  expect_identical(aa_col_types(fake_conn("PqConnection"))$ts, "VARCHAR(19)")
  expect_identical(aa_col_types(fake_conn("PqConnection"))$key, "VARCHAR(255)")
})

test_that("нарушение уникальности распознаётся во всех базах", {
  expect_true(aa_is_unique_violation(simpleError("UNIQUE constraint failed: users.login")))
  expect_true(aa_is_unique_violation(simpleError("Duplicate entry 'a' for key 'users.login'")))
  expect_true(aa_is_unique_violation(simpleError("duplicate key value violates unique constraint")))
  expect_true(aa_is_unique_violation(simpleError("Constraint Error: Duplicate key \"login: a\" violates unique constraint.")))
  expect_false(aa_is_unique_violation(simpleError("no such table: users")))
})

test_that("integer64 из результата приводится к числам", {
  skip_if_not_installed("bit64")

  x <- data.frame(n = bit64::as.integer64(3), s = "a")
  res <- aa_fix_integers(x)

  expect_false(inherits(res$n, "integer64"))
  expect_equal(res$n, 3)
})
