# Dialect layer: checks without a live database (connections are faked with classes).

fake_conn <- function(class) structure(list(), class = class)

test_that("the dialect is detected by connection class", {
  expect_identical(aa_dialect(fake_conn("SQLiteConnection")), "sqlite")
  expect_identical(aa_dialect(fake_conn("duckdb_connection")), "duckdb")
  expect_identical(aa_dialect(fake_conn("MariaDBConnection")), "mysql")
  expect_identical(aa_dialect(fake_conn("PqConnection")), "postgres")
  expect_true(is.na(aa_dialect(list())))
  expect_true(is.na(aa_dialect(fake_conn("BigQueryConnection"))))
})

test_that("an unsupported database is rejected with a clear error", {
  expect_error(
    aa_check_conn(fake_conn("BigQueryConnection")),
    class = "appauth_error_connection"
  )
  expect_error(
    aa_check_conn("not a connection"),
    class = "appauth_error_connection"
  )
})

test_that("placeholders become $n only for PostgreSQL", {
  sql <- "UPDATE users SET role = ? WHERE login = ? AND blocked = ?"
  pg <- fake_conn("PqConnection")

  expect_identical(
    aa_prepare_sql(pg, sql),
    "UPDATE users SET role = $1 WHERE login = $2 AND blocked = $3"
  )
  expect_identical(aa_prepare_sql(pg, "SELECT 1"), "SELECT 1")
  expect_identical(aa_prepare_sql(pg, "SELECT ?"), "SELECT $1")

  for (cls in c("SQLiteConnection", "duckdb_connection", "MariaDBConnection")) {
    expect_identical(aa_prepare_sql(fake_conn(cls), sql), sql)
  }
})

test_that("aa_utc returns a UTC string and an offset in seconds", {
  now <- as.POSIXct("2026-11-05 10:00:00", tz = "UTC")

  expect_identical(aa_utc(0, now), "2026-11-05 10:00:00")
  expect_identical(aa_utc(3600, now), "2026-11-05 11:00:00")
  expect_identical(aa_utc(-86400, now), "2026-11-04 10:00:00")
})

test_that("\"insert if missing\" is written per dialect", {
  cols <- c("version", "name")

  expect_match(
    aa_insert_ignore_sql(fake_conn("MariaDBConnection"), "t", cols),
    "^INSERT IGNORE INTO t"
  )
  expect_match(
    aa_insert_ignore_sql(fake_conn("PqConnection"), "t", cols),
    "ON CONFLICT DO NOTHING$"
  )
  expect_match(
    aa_insert_ignore_sql(fake_conn("SQLiteConnection"), "t", cols),
    "ON CONFLICT DO NOTHING$"
  )
})

test_that("column types and auto-increment depend on the database", {
  expect_match(
    aa_pk_column(fake_conn("SQLiteConnection"), "users"),
    "AUTOINCREMENT"
  )
  expect_match(
    aa_pk_column(fake_conn("MariaDBConnection"), "users"),
    "AUTO_INCREMENT"
  )
  expect_match(
    aa_pk_column(fake_conn("PqConnection"), "users"),
    "GENERATED BY DEFAULT AS IDENTITY"
  )

  expect_identical(aa_col_types(fake_conn("SQLiteConnection"))$ts, "TEXT")
  expect_identical(aa_col_types(fake_conn("PqConnection"))$ts, "VARCHAR(19)")
  expect_identical(aa_col_types(fake_conn("PqConnection"))$key, "VARCHAR(255)")
})

test_that("a uniqueness violation is recognized in all databases", {
  expect_true(aa_is_unique_violation(simpleError(
    "UNIQUE constraint failed: users.login"
  )))
  expect_true(aa_is_unique_violation(simpleError(
    "Duplicate entry 'a' for key 'users.login'"
  )))
  expect_true(aa_is_unique_violation(simpleError(
    "duplicate key value violates unique constraint"
  )))
  expect_true(aa_is_unique_violation(simpleError(
    "Constraint Error: Duplicate key \"login: a\" violates unique constraint."
  )))
  expect_false(aa_is_unique_violation(simpleError("no such table: users")))
})

test_that("integer64 in a result is converted to numbers", {
  skip_if_not_installed("bit64")

  x <- data.frame(n = bit64::as.integer64(3), s = "a")
  res <- aa_fix_integers(x)

  expect_false(inherits(res$n, "integer64"))
  expect_equal(res$n, 3)
})

test_that("write sections commit, roll back and support nesting", {
  con <- users_db()

  aa_write_section(con, function() {
    raw_user(con, "ann")
    aa_write_section(con, function() {
      aa_execute(
        con,
        "UPDATE users SET role = ? WHERE login = ?",
        params = list("admin", "ann")
      )
    })
  })
  expect_identical(aa_get_user(con, "ann")$role, "admin")

  expect_error(
    aa_write_section(con, function() {
      raw_user(con, "bob")
      stop("boom")
    }),
    "boom"
  )

  expect_equal(tquery(con, "SELECT COUNT(*) AS n FROM users")$n, 1)
  DBI::dbDisconnect(con)
})
